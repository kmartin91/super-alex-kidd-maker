ICONS.redo = ICONS.undo.map((r) => [...r].reverse().join(''));

// <svg> element for an icon, `scale` screen pixels per icon pixel.
export function icon(name, scale = 2) {
  const rows = ICONS[name];
  const w = rows[0].length, h = rows.length;
  let rects = '';
  rows.forEach((r, y) => {
    for (let x = 0; x < w; x++) {
      if (r[x] !== '#') continue;
      let n = 1;
      while (r[x + n] === '#') n++;
      rects += `<rect x="${x}" y="${y}" width="${n}" height="1"/>`;
      x += n - 1;
    }
  });
  const span = document.createElement('span');
  span.className = 'px-icon';
  span.innerHTML = `<svg viewBox="0 0 ${w} ${h}" width="${w * scale}" height="${h * scale}" ` +
    `shape-rendering="crispEdges" fill="currentColor" aria-hidden="true">${rects}</svg>`;
  return span;
}

// Replaces every <i data-icon="name" data-scale="n"> in the page.
export function renderIcons(root = document) {
  root.querySelectorAll('i[data-icon]').forEach((el) => {
    el.replaceWith(icon(el.dataset.icon, Number(el.dataset.scale) || 2));
  });
}
